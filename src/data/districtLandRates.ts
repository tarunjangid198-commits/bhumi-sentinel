/**
 * Calculates statutory compensation under RFCTLARR Act 2013:
 * 1. Base Market Value = DLC rate * multiplier factor (1.0 in urban, 1.25 to 2.0 in rural)
 * 2. 100% Solatium added
 * 3. 12% statutory interest per annum from Section 4(1) notice
 */
export function calculateRfctlarrAward(
  areaInSqM: number,
  dlcRatePerSqM: number,
  ruralMultiplier: number = 1.25,
  elapsedMonths: number = 12
) {
  const baseDlcValue = areaInSqM * dlcRatePerSqM;
  const marketValueWithMultiplier = baseDlcValue * ruralMultiplier;
  const solatium = marketValueWithMultiplier; // 100% Solatium under Section 30(1)
  const additionalInterest = marketValueWithMultiplier * 0.12 * (elapsedMonths / 12); // 12% p.a under Section 30(3)
  const totalAward = marketValueWithMultiplier + solatium + additionalInterest;

  return {
    baseDlcValue,
    marketValueWithMultiplier,
    solatium,
    additionalInterest,
    totalAward,
    solatiumPercentage: 100,
    annualInterestRatePct: 12,
  };
}
