// Area conversion constants relative to Square Meters (m²)
export const AREA_CONVERSION_TO_SQM = {
  sqMeter: 1,
  sqFoot: 0.092903, // 1 sq.ft = 0.092903 sq.m
  acre: 4046.8564224, // 1 acre = 4,046.86 sq.m
  hectare: 10000, // 1 ha = 10,000 sq.m
  bigha: 2529.285264, // 1 Pucca Bigha (Rajasthan standard) = 2,529.28 sq.m (5/8 of an acre)
  gaj: 0.836127, // 1 Gaj / Sq.Yard = 9 sq.ft = 0.836127 sq.m
};

export type AreaUnit = 'sqMeter' | 'sqFoot' | 'acre' | 'hectare' | 'bigha' | 'gaj';

export const UNIT_LABELS: Record<AreaUnit, string> = {
  sqMeter: 'Square Meters (m²)',
  sqFoot: 'Square Feet (ft²)',
  acre: 'Acres (ac)',
  hectare: 'Hectares (ha)',
  bigha: 'Pucca Bighas (बड़ा बीघा)',
  gaj: 'Square Yards / Gaj (वर्ग गज)',
};

/**
 * Converts area from one unit to all other units
 */
export function convertAreaToAll(value: number, fromUnit: AreaUnit) {
  const inSqM = value * AREA_CONVERSION_TO_SQM[fromUnit];
  return {
    sqMeter: inSqM,
    sqFoot: inSqM / AREA_CONVERSION_TO_SQM.sqFoot,
    acre: inSqM / AREA_CONVERSION_TO_SQM.acre,
    hectare: inSqM / AREA_CONVERSION_TO_SQM.hectare,
    bigha: inSqM / AREA_CONVERSION_TO_SQM.bigha,
    gaj: inSqM / AREA_CONVERSION_TO_SQM.gaj,
  };
}

/**
 * Calculates rates across all units given a base rate per Square Meter
 */
export function calculateAllUnitRates(baseRatePerSqM: number) {
  return {
    ratePerSqMeter: Math.round(baseRatePerSqM),
    ratePerSqFoot: Number((baseRatePerSqM * AREA_CONVERSION_TO_SQM.sqFoot).toFixed(1)),
    ratePerAcre: Math.round(baseRatePerSqM * AREA_CONVERSION_TO_SQM.acre),
    ratePerHectare: Math.round(baseRatePerSqM * AREA_CONVERSION_TO_SQM.hectare),
    ratePerBigha: Math.round(baseRatePerSqM * AREA_CONVERSION_TO_SQM.bigha),
    ratePerGaj: Number((baseRatePerSqM * AREA_CONVERSION_TO_SQM.gaj).toFixed(1)),
  };
}

